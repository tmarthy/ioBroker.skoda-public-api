/**
 * Creates a translated command-button label from a known command-domain label.
 *
 * @param en English command-domain label.
 * @param de German command-domain label.
 * @param action Command action.
 */
export function translatedCommandAction(en: ObjectNameKey, de: string, action: 'start' | 'stop'): CompleteObjectName {
	const domain = translated(en, de);
	const verb = COMMAND_ACTIONS[action];
	return Object.fromEntries(
		OBJECT_NAME_LANGUAGES.map(language => [language, `${domain[language]} - ${verb[language]}`]),
	) as CompleteObjectName;
}

/**
 * Returns whether an existing name is an older, unmodified adapter default.
 *
 * @param existing Currently stored object name.
 * @param target Complete current adapter default.
 * @param legacyNames Earlier English defaults that are safe to replace.
 */
export function isIncompleteDefaultObjectName(
	existing: ioBroker.StringOrTranslated,
	target: CompleteObjectName,
	legacyNames: readonly string[] = [],
): boolean {
	if (typeof existing === 'string') {
		return existing === target.en || legacyNames.includes(existing);
	}
	const entries = Object.entries(existing);
	return (
		entries.length > 0 &&
		entries.length < OBJECT_NAME_LANGUAGES.length &&
		entries.every(([language, value]) => target[language as keyof CompleteObjectName] === value)
	);
}
