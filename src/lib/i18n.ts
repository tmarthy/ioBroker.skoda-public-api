/** English keys of the centrally maintained object-name catalog. */
export type ObjectNameKey = keyof typeof OBJECT_NAME_TRANSLATIONS;

/**
 * Creates complete object metadata for all ioBroker languages.
 *
 * Unknown API fields deliberately do not call this function; they retain a plain
 * string name. Consequently an incomplete translation object can never be emitted.
 *
 * @param en English adapter-defined label and catalog key.
 * @param de German adapter-defined label.
 */
export function translated(en: ObjectNameKey, de: string): CompleteObjectName {
	const [ru, pt, nl, fr, it, es, pl, uk, zhCn] = OBJECT_NAME_TRANSLATIONS[en];
	return { en, de, ru, pt, nl, fr, it, es, pl, uk, 'zh-cn': zhCn };
}

