/**
 * Translate a stable diagnostic code, falling back to its English label.
 *
 * @param code Stable code.
 * @param english English fallback.
 * @param language ioBroker system language.
 */
export function diagnosticText(code: string, english: string, language: string): string {
	const index = LANGUAGES.indexOf(language as (typeof LANGUAGES)[number]);
	return index < 0 ? english : (TEXT[code as keyof typeof TEXT]?.[index] ?? english);
}

/**
 * Build localized common.states while preserving machine-readable state values.
 *
 * @param labels English labels by stable code.
 * @param language ioBroker system language.
 */
export function diagnosticStates(labels: Record<string, string>, language: string): Record<string, string> {
	return Object.fromEntries(
		Object.entries(labels).map(([key, value]) => [key, diagnosticText(key, value, language)]),
	);
}
